// Static checks of the Greenbar front end (no browser, no dependencies). They guard against the
// failure modes of a re-skin: a selector the code needs that moved, a control hidden by CSS,
// a class with no style, a lost UNAVAILABLE label, remote assets, colour-only status, or a
// preview.html that needs a server.
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rd = (...p) => fs.readFileSync(path.join(ROOT, ...p), 'utf8');
const HTML = rd('public', 'index.html'), APP = rd('public', 'js', 'app.js'), BRAND = rd('public', 'js', 'brand.js'), RING = rd('public', 'js', 'ring.js');
const CSS = rd('public', 'css', 'greenbar.css'), CFG = rd('public', 'site.config.js');
const stripMedia = (css, re) => { // remove @media blocks whose condition matches re (balanced braces)
  let out = '', i = 0; while (i < css.length) { const m = css.indexOf('@media', i); if (m < 0) { out += css.slice(i); break; } const open = css.indexOf('{', m); const cond = css.slice(m, open);
    let d = 1, j = open + 1; for (; j < css.length && d; j++) d += css[j] === '{' ? 1 : css[j] === '}' ? -1 : 0;
    out += css.slice(i, m) + (re.test(cond) ? '' : css.slice(m, j)); i = j; } return out; };
const rules = (css) => [...css.replace(/\/\*[\s\S]*?\*\//g, '').matchAll(/([^{}]+)\{([^{}]*)\}/g)].map((m) => ({ sel: m[1].trim(), body: m[2] }));
const htmlIds = new Set([...HTML.matchAll(/\bid="([^"]+)"/g)].map((m) => m[1]));

test('every element id the scripts look up exists in index.html or is generated by the scripts', () => {
  const used = new Set([...APP.matchAll(/\$\('([^']+)'\)/g), ...BRAND.matchAll(/\$\('([^']+)'\)/g)].map((m) => m[1]));
  const generated = /^(pc\d(-[vck])?|k-\w+(-k)?|mk-\w+(-k)?|tab-more)$/; // built from templates in app.js / brand.js
  const missing = [...used].filter((id) => !htmlIds.has(id) && !generated.test(id));
  assert.deepEqual(missing, [], 'ids used by scripts but absent from index.html: ' + missing.join(', '));
  for (const id of ['ring', 'stage', 'nav', 'side', 'scrim', 'menu-btn', 'side-close', 'feed', 'ctl-pause', 'ctl-pause2', 'ctl-reset', 'reset-dlg', 'reset-in', 'banner', 'run-pg', 'run-no', 'run-date', 'footer', 'toast']) assert.ok(htmlIds.has(id), id);
});

test('ids are unique in index.html', () => {
  const all = [...HTML.matchAll(/\bid="([^"]+)"/g)].map((m) => m[1]); const dup = all.filter((v, i) => all.indexOf(v) !== i);
  assert.deepEqual(dup, []);
});

test('every class used by markup and scripts has a Greenbar style', () => {
  const classes = new Set();
  for (const src of [HTML, APP, BRAND]) for (const m of src.matchAll(/class="([^"$]*)"/g)) m[1].split(/\s+/).filter(Boolean).forEach((c) => classes.add(c));
  // classes that are only hooks for scripts, or are styled through a parent/compound selector
  const hookOnly = new Set(['nav', 'smp', 'kl', 'n', 'k', 'f', 'q', 'go', 'win', 'xb']);
  const missing = [...classes].filter((c) => !/^[a-z]/i.test(c) ? false : !hookOnly.has(c) && !new RegExp('\\.' + c.replace(/[-]/g, '\\-') + '(?![\\w-])').test(CSS));
  assert.deepEqual(missing, [], 'classes without any rule in greenbar.css: ' + missing.join(', '));
});

test('CSS never hides the controls, provenance badges or paper labels (outside print and the desktop-only drawer chrome)', () => {
  const css = stripMedia(stripMedia(CSS, /print/), /min-width:\s*1100px/);
  const hiding = rules(css).filter((r) => /display\s*:\s*none|visibility\s*:\s*hidden|opacity\s*:\s*0(?![.\d])/.test(r.body));
  const protectedSel = /#ctl-pause|#ctl-pause2|#ctl-reset|\.top-r(?![\w-])|\.btn(?![\w-])|\.feedpill|\.src(?![\w-])|\.unavail|\.paper-flag|\.stamp|\.tag|#bl-save|#led-csv|\.seg(?![\w-])|\.explain|\.banner|\.state(?![\w-])|\.mode-card|\.nav(?![\w-])|\.tabbar(?![\w-])|#menu-btn|\.menu-btn/;
  const bad = hiding.filter((r) => r.sel.split(',').some((s) => protectedSel.test(s) && !/(::before|::after|\.smp|:empty|\.hero span|\[hidden\])/.test(s)));
  assert.deepEqual(bad.map((r) => r.sel), []);
  // the toast and the trade slip start transparent on purpose; they must have a visible state
  assert.match(CSS, /#toast\.show\{opacity:1/); assert.match(CSS, /\.trade\.show\{opacity:1/);
  // the earlier theme hid the top Pause button on phones; Greenbar must not
  assert.doesNotMatch(CSS, /\.top-r \.btn\.sm\{display:none/);
});

test('responsive audit: breakpoints, drawer vs sidebar, tab strip, no wide fixed widths outside media queries', () => {
  for (const bp of ['max-width:639.98px', 'min-width:640px', 'min-width:900px', 'min-width:1100px', 'min-width:1440px']) assert.ok(CSS.includes('@media (' + bp + ')'), bp);
  assert.match(HTML, /<meta name="viewport" content="width=device-width, initial-scale=1">/);
  const desk = CSS.slice(CSS.indexOf('@media (min-width:1100px)'));
  assert.match(desk, /\.side\{transform:none/, 'sidebar pinned on desktop');
  assert.match(desk, /\.side-close,\.menu-btn,\.scrim,\.tabbar,#tab-more\{display:none!important\}/, 'drawer chrome hidden only on desktop');
  assert.match(CSS, /\.side\.open\{transform:none/, 'drawer opens on small screens');
  const base = stripMedia(CSS, /./);
  const wide = [...base.matchAll(/(?<![-\w])(width|min-width|grid-template-columns)\s*:[^;}]*?(\d{3,})px/g)].filter((m) => Number(m[2]) > 360);
  assert.deepEqual(wide.map((m) => m[0]), [], 'fixed widths above 360px outside media queries would overflow phones');
  assert.match(CSS, /\.scroll\{overflow:auto/, 'wide tables scroll inside their panel');
  assert.match(CSS, /body\{[^}]*overflow-x:hidden/);
});

test('accessibility: focus ring, reduced motion, non-colour status cues, keyboard rows', () => {
  assert.match(CSS, /:focus-visible\{outline:3px solid/);
  assert.match(CSS, /@media \(prefers-reduced-motion:reduce\)\{\*,\*::before,\*::after\{animation:none!important;transition:none!important/);
  assert.match(RING, /prefers-reduced-motion: reduce/); assert.match(RING, /pulse\(id, big\) \{ if \(RM\.matches\) return;/);
  // families are identified by glyph shapes, not by coloured dots
  assert.doesNotMatch(APP, /class="dot"/); assert.doesNotMatch(APP, /hsl\(/);
  for (let i = 0; i < 6; i++) assert.ok(CSS.includes(`.gl.g${i}`), 'glyph ' + i);
  // evidence matrix and decision bars differ by shape/fill pattern, not only colour
  assert.match(CSS, /\.mx i\.f::after\{content:'×'\}/); assert.match(CSS, /\.mx i\.m::after\{content:'\?'\}/);
  assert.match(CSS, /\.cb i\.no\{background:repeating-linear-gradient/);
  // feed status: filled / half / empty square plus the state word in the text
  assert.match(APP, /fp\.textContent = `FEED \$\{f\.state\.toUpperCase\(\)\}/);
  assert.match(CSS, /\.feedpill\.live::before\{background:currentColor\}/); assert.match(CSS, /\.feedpill\.stale::before\{background:transparent\}/);
  // clickable list rows are reachable and operable from the keyboard
  for (const list of ['fam-list', 'play-list', 'pf-list']) assert.match(APP, new RegExp(`paintList\\('${list}'`));
  assert.equal((APP.match(/tabindex=\\?"0\\?" role=\\?"button\\?"/g) || []).length, 3);
  assert.match(APP, /e\.key !== 'Enter' && e\.key !== ' '/);
});

test('colour contrast of Greenbar inks on paper and on the mint band is at least WCAG AA (4.5:1)', () => {
  const lum = (hex) => { const c = hex.match(/\w\w/g).map((h) => parseInt(h, 16) / 255).map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4)); return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]; };
  const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };
  const v = (name) => CSS.match(new RegExp(`--${name}:(#[0-9a-f]{6})`))[1];
  for (const bg of ['paper', 'bar', 'manila']) for (const fg of ['ink', 'ink2', 'mu', 'dim', 'red', 'ochre', 'green']) {
    const r = ratio(v(fg), v(bg)); assert.ok(r >= 4.5, `${fg} on ${bg}: ${r.toFixed(2)}`);
  }
  assert.ok(ratio('#fbfbf6', '#1f231d') >= 7, 'inverted rows'); assert.ok(ratio('#fbfbf6', '#a2372e') >= 4.5, 'white on red');
});

test('UNAVAILABLE pages and panels stay labelled and honest', () => {
  for (const id of ['backtest', 'narr', 'devhunt', 'lab']) {
    assert.match(CFG, new RegExp(`id: '${id}',[^\\n]*na: true,[^\\n]*description: 'Unavailable`), id + ' marked na + Unavailable');
    assert.ok(htmlIds.has('pg-' + id) && htmlIds.has('why-' + id), id + ' page + explanation slot');
  }
  for (const src of ['backtest', 'metas', 'devhunt', 'lab', 'holders', 'chain']) assert.match(HTML, new RegExp(`data-src="${src}"`), src);
  assert.match(HTML, /<h3>Holder agents<\/h3>/); assert.match(HTML, /<h3>On-chain wallets<\/h3>/);
  assert.match(BRAND, /<span class="nna">N\/A<\/span><span class="sr"> \(unavailable in this version\)<\/span>/);
  assert.match(APP, /meta\.na \? ' · unavailable' : ''/);
  assert.match(CSS, /\.unavail::before\{content:'VOID · UNAVAILABLE IN THIS VERSION'/);
  assert.match(CFG, /'common\.srcUnavailable': 'UNAVAILABLE'/); assert.match(CFG, /'common\.srcLive': 'LIVE FEED'/); assert.match(CFG, /'common\.srcPaper': 'PAPER · virtual'/);
  assert.match(APP, /simulated fill/); assert.match(HTML, /PAPER TRADING<\/b>virtual USD only/);
});

test('local typography only: Courier Prime 400/700 roman + italic, no remote assets', () => {
  for (const [w, s] of [[400, 'normal'], [400, 'italic'], [700, 'normal'], [700, 'italic']]) {
    assert.match(CSS, new RegExp(`courier-prime-${w}-${s}\\.woff2\\) format\\('woff2'\\);font-weight:${w};font-style:${s}`));
    assert.ok(fs.statSync(path.join(ROOT, 'public', 'fonts', `courier-prime-${w}-${s}.woff2`)).size > 10000);
  }
  assert.ok(fs.existsSync(path.join(ROOT, 'public', 'fonts', 'OFL-CourierPrime.txt')));
  assert.doesNotMatch(CSS, /https?:\/\//); assert.doesNotMatch(HTML, /(src|href)="https?:/); assert.doesNotMatch(RING + APP + BRAND, /fonts\.googleapis|cdn\.|unpkg|jsdelivr/);
  assert.doesNotMatch(APP, /'(9|11)px JB'/, 'canvas text uses the shipped font');
});

test('preview.html is a standalone, script-free, clearly labelled example', () => {
  const P = rd('preview.html');
  assert.doesNotMatch(P, /<script/i); assert.doesNotMatch(P, /fetch\(|EventSource|import\s/);
  assert.doesNotMatch(P, /(src|href)="(https?:)?\/\//); assert.doesNotMatch(P, /(src|href)="\//, 'only relative paths work from disk');
  assert.match(P, /DESIGN PREVIEW/); assert.match(P, /EXAMPLE DATA ONLY/); assert.match(P, /START\.bat/);
  assert.doesNotMatch(P, />LIVE FEED</, 'preview never shows a bare LIVE FEED badge');
  for (const m of P.matchAll(/(?:src|href)="([^"#:]+)"/g)) assert.ok(fs.existsSync(path.join(ROOT, m[1])), 'missing ' + m[1]);
  assert.doesNotMatch(P, /seed phrase"|type="password"|connect wallet/i);
});
